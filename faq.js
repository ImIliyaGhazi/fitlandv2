const cats = document.querySelector(".faq-cats");
const list = document.getElementById("faq-list");

function paint(id) {
  const group = FAQ.find((item) => item.id === id) || FAQ[0];
  cats.querySelectorAll(".faq-cat").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.cat === group.id);
  });
  list.innerHTML = group.items
    .map(
      ([question, answer], index) => `
        <article class="faq-item${index === 0 ? " is-open" : ""}">
          <h2>
            <button type="button" aria-expanded="${index === 0 ? "true" : "false"}">
              <span>${question}</span>
              <i class="bi bi-chevron-down" aria-hidden="true"></i>
            </button>
          </h2>
          <p class="faq-item__a">${answer}</p>
        </article>`
    )
    .join("");
}

cats.addEventListener("click", (event) => {
  const button = event.target.closest(".faq-cat");
  if (!button) return;
  paint(button.dataset.cat);
});

list.addEventListener("click", (event) => {
  const button = event.target.closest(".faq-item button");
  if (!button) return;
  const item = button.closest(".faq-item");
  const open = !item.classList.contains("is-open");
  item.classList.toggle("is-open", open);
  button.setAttribute("aria-expanded", open ? "true" : "false");
});

paint("order");
